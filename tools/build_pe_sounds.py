# -*- coding: utf-8 -*-
"""
给 PEVersion（file:// 双击版）生成内嵌音效包 js/sounds.js。

游戏 audio.js 在 location.protocol === 'file:' 时会加载 js/sounds.js，
期望格式：
  window.SOUNDS = { events: {事件名: [{name,volume,pitch,weight}...]}, files: {name: base64} }

本脚本：
  1. 从 PEVersion/js/sound_events.js 取 window.SOUND_EVENTS（原样保留事件表）
  2. 把 PEVersion/sounds/sfx/ 下全部 .m4a 以 base64 内联进 files
  3. 流式写出（不把 68MB 一次性拼进内存）

用法：python tools/build_pe_sounds.py [目标目录，默认 PEVersion]
"""
import base64, json, os, re, sys, io

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DST = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else os.path.join(ROOT, 'PEVersion')
EVENTS = os.path.join(DST, 'js', 'sound_events.js')
SFX = os.path.join(DST, 'sounds', 'sfx')
OUT = os.path.join(DST, 'js', 'sounds.js')

for p in (EVENTS, SFX):
    if not os.path.exists(p):
        sys.exit('缺少: ' + p)

# 事件表：直接取原文里的 JSON 对象字面量
s = open(EVENTS, encoding='utf-8').read()
m = re.search(r'window\.SOUND_EVENTS\s*=\s*(\{.*\})\s*;', s, re.S)
if not m:
    sys.exit('sound_events.js 里没找到 SOUND_EVENTS')
events_json = m.group(1)
try:
    events = json.loads(events_json)
except Exception as e:
    sys.exit('SOUND_EVENTS 不是合法 JSON: %s' % e)

# 收集文件：key 是相对 sfx/ 去掉扩展名（与事件里的 name 一致）
files = []
have = set()
for d, _, fs in os.walk(SFX):
    for f in fs:
        if not f.lower().endswith('.m4a'):
            continue
        full = os.path.join(d, f)
        rel = os.path.relpath(full, SFX).replace('\\', '/')[:-4]
        files.append((rel, full))
        have.add(rel)
files.sort()
print('音效文件 %d 个' % len(files))

# 校验：事件引用的名字是不是都能找到
wanted = set()
for ev, arr in events.items():
    if isinstance(arr, list):
        for it in arr:
            if isinstance(it, dict) and it.get('name'):
                wanted.add(it['name'])
missing = sorted(wanted - have)
print('事件引用 %d 个名字，缺失 %d 个' % (len(wanted), len(missing)))
if missing:
    print('  样例:', missing[:8])

# 流式写：事件表 + 全部 base64
n = 0
with io.open(OUT, 'w', encoding='utf-8', newline='\n') as out:
    out.write('// Generated by tools/build_pe_sounds.py - do not edit.\n')
    out.write('// file:// 双击版专用：%d 个 m4a 内嵌，audio.js 直接读 SOUNDS.files。\n' % len(files))
    out.write('window.SOUNDS = {events: ')
    out.write(events_json)
    out.write(', files:{\n')
    for name, full in files:
        with open(full, 'rb') as fh:
            b64 = base64.b64encode(fh.read()).decode('ascii')
        out.write('%s:%s,\n' % (json.dumps(name, ensure_ascii=False), json.dumps(b64)))
        n += 1
        if n % 1000 == 0:
            print('  %d/%d' % (n, len(files)))
    out.write('}};\n')

sz = os.path.getsize(OUT)
print('已写出 %s (%.1f MB)' % (OUT, sz / 1024 / 1024))
